import { readdir, readFile, writeFile, lstat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const slug = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const semver = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*)?(?:\+[0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*)?$/;

export function validateMetadata(value, directory) {
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("Feature metadata must be an object");
  const expected = ["id", "name", "description", "version", "tags", "author"];
  for (const key of Object.keys(value)) {
    if (!expected.includes(key)) throw new Error("Unknown metadata field: " + key);
  }
  for (const key of ["id", "name", "description", "version", "author"]) {
    if (typeof value[key] !== "string" || !value[key].trim()) throw new Error("Missing feature " + key);
  }
  if (!slug.test(value.id) || value.id === "zeonest" || value.id !== directory) {
    throw new Error("Feature ID must match its kebab-case directory and cannot be zeonest");
  }
  if (!semver.test(value.version)) throw new Error("Feature version must be valid SemVer");
  if (!Array.isArray(value.tags) || value.tags.some((tag) => typeof tag !== "string" || !tag.trim())) {
    throw new Error("Feature tags must be non-empty strings");
  }
  if (new Set(value.tags).size !== value.tags.length) throw new Error("Feature tags must be unique");
  return Object.fromEntries(expected.map((key) => [key, value[key]]));
}

async function exists(file) {
  try {
    const info = await lstat(file);
    if (!info.isFile()) throw new Error("Expected a regular file: " + file);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

async function directories(dir) {
  try {
    return (await readdir(dir, { withFileTypes: true }))
      .filter((entry) => !entry.name.startsWith("."))
      .map((entry) => {
        if (!entry.isDirectory()) throw new Error("Expected a feature directory: " + path.join(dir, entry.name));
        return entry.name;
      }).sort();
  } catch (error) {
    if (error.code === "ENOENT") return [];
    throw error;
  }
}

async function entry(root, runtime, id, name) {
  const base = runtime + "/features/" + id + "/" + name;
  const candidates = [];
  for (const extension of [".ts", ".tsx"]) {
    if (await exists(path.join(root, base + extension))) candidates.push(base + extension);
  }
  if (candidates.length > 1) throw new Error("Ambiguous feature entry: " + base);
  return candidates[0];
}

export async function loadFeatures(root = projectRoot) {
  const ids = await directories(path.join(root, "features"));
  for (const runtime of ["client", "server", "shared"]) {
    for (const id of await directories(path.join(root, runtime, "features"))) {
      if (!ids.includes(id)) throw new Error("Missing features/" + id + "/feature.json");
    }
  }
  const features = [];
  for (const id of ids) {
    const metadata = validateMetadata(JSON.parse(await readFile(path.join(root, "features", id, "feature.json"), "utf8")), id);
    const client = await entry(root, "client", id, "index");
    const server = await entry(root, "server", id, "index");
    const clientSettings = await entry(root, "client", id, "settings");
    const serverSettings = await entry(root, "server", id, "settings");
    if (!client && !server) throw new Error("Feature needs a client or server entry: " + id);
    features.push({ metadata, client, server, clientSettings, serverSettings });
  }
  return features;
}

function importPath(file, runtime) {
  return "./" + file.slice(runtime.length + 1).replace(/\.tsx?$/, "");
}

export function renderManifests(features) {
  const banner = "// Generated by tools/features.mjs. Do not edit.\n";
  const catalog = banner + 'import type { FeatureMetadata } from "./catalog";\n\n'
    + "export const featureCatalog: readonly FeatureMetadata[] = "
    + JSON.stringify(features.map(({ metadata }) => metadata), null, 2) + ";\n";
  const clientImports = [];
  const serverImports = [];
  const clientEntries = [];
  const serverEntries = [];
  const screens = [];
  const settings = [];
  features.forEach((feature, index) => {
    const key = JSON.stringify(feature.metadata.id);
    for (const runtime of ["client", "server"]) {
      if (feature[runtime]) {
        const alias = "feature" + index;
        (runtime === "client" ? clientImports : serverImports)
          .push("import " + alias + " from " + JSON.stringify(importPath(feature[runtime], runtime)) + ";");
        (runtime === "client" ? clientEntries : serverEntries).push("  " + key + ": " + alias + ",");
      }
    }
    if (feature.clientSettings) {
      clientImports.push("import settings" + index + " from " + JSON.stringify(importPath(feature.clientSettings, "client")) + ";");
      screens.push("  " + key + ": settings" + index + ",");
    }
    if (feature.serverSettings) {
      serverImports.push("import settings" + index + " from " + JSON.stringify(importPath(feature.serverSettings, "server")) + ";");
      settings.push("settings" + index);
    }
  });
  const object = (entries) => entries.length ? "{\n" + entries.join("\n") + "\n}" : "{}";
  return {
    "shared/catalog.generated.ts": catalog,
    "client/features.generated.ts": banner
      + 'import type { PluginClientContribution, PluginSettingsScreenContribution } from "@getpaseo/plugin/client";\n'
      + (clientImports.length ? clientImports.join("\n") + "\n" : "") + "\n"
      + "export const featureContributions: Readonly<Record<string, PluginClientContribution>> = " + object(clientEntries) + ";\n"
      + "export const featureSettingsScreens: Readonly<Record<string, PluginSettingsScreenContribution>> = " + object(screens) + ";\n",
    "server/features.generated.ts": banner
      + 'import type { PluginServerContribution } from "@getpaseo/plugin/server";\n'
      + (serverImports.length ? serverImports.join("\n") + "\n" : "") + "\n"
      + "export const featureContributions: Readonly<Record<string, PluginServerContribution>> = " + object(serverEntries) + ";\n"
      + "export const featureSettingsContributions: readonly PluginServerContribution[] = [" + settings.join(", ") + "];\n",
  };
}

export async function syncFeatures(root = projectRoot, check = false) {
  const rendered = renderManifests(await loadFeatures(root));
  const stale = [];
  for (const [relative, content] of Object.entries(rendered)) {
    const target = path.join(root, relative);
    let current;
    try { current = await readFile(target, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
    if (current === content) continue;
    stale.push(relative);
    if (!check) await writeFile(target, content);
  }
  if (check && stale.length) throw new Error("Stale generated manifests: " + stale.join(", ") + ". Run npm run features:sync.");
  return stale;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.slice(2).some((arg) => arg !== "--check")) throw new Error("Usage: node tools/features.mjs [--check]");
    const check = process.argv.includes("--check");
    const changed = await syncFeatures(projectRoot, check);
    console.log(check ? "Static manifests are current." : "Updated " + changed.length + " static manifests.");
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
